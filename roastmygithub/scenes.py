AREA_HEIGHT = 1370
MARGIN = 80
VIZ_TOP = 470  # the visual sits under the headline, from here to the bottom of the area
VIZ_BOTTOM = AREA_HEIGHT - 30

Draw = Callable[[Image.Image, float, float], None]

