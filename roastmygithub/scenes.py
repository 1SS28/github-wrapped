"""Animated scenes: one per beat, drawn from the person's real GitHub data.

Every scene is a function of time. `make_scene()` picks the visual that fits a highlight (the
contribution graph for streaks and gaps, a 24-hour clock for late nights, a terminal running
`git log` for commit messages, ...) and returns `draw(area, t, duration)`, which paints one
frame of the scene onto `area`, a 1080 x AREA_HEIGHT image, `t` seconds into the beat.

Each scene opens with the beat's headline (ROAST / PROPS, the figure counting up, its label)
and then animates its visual underneath. Nothing here is generated by AI: the figures,
commit messages and repository names are the user's own, and private ones never get here
unless --include-private was passed (see stats.py).
"""

