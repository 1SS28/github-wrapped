# -- Small helpers ---------------------------------------------------------------------


def clamp(x: float, low: float = 0.0, high: float = 1.0) -> float:
    return max(low, min(high, x))


def ease_out(x: float) -> float:
    x = clamp(x)
    return 1 - (1 - x) ** 3


def ease_in_out(x: float) -> float:
    x = clamp(x)
    return 4 * x**3 if x < 0.5 else 1 - (-2 * x + 2) ** 3 / 2


def phase(t: float, start: float, length: float) -> float:
    """0 before `start`, rising to 1 over `length` seconds."""
    return clamp((t - start) / length) if length > 0 else float(t >= start)


def mix(a: RGB, b: RGB, k: float) -> RGB:
    k = clamp(k)
    return tuple(round(x + (y - x) * k) for x, y in zip(a, b))  # type: ignore[return-value]


def hex_rgb(value: str) -> RGB:
    value = value.lstrip("#")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


@functools.lru_cache(maxsize=None)
def mono(size: int) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    for candidate in _MONO:
        if Path(candidate).exists():
            return ImageFont.truetype(candidate, size)
    return ImageFont.load_default(size)


@functools.lru_cache(maxsize=None)
def sans(size: int, bold: bool = True) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    return font(size, bold)


def fit(draw: ImageDraw.ImageDraw, text: str, max_width: int, start: int, smallest: int, bold: bool = True):
    size = start
    while size > smallest and draw.textlength(text, font=sans(size, bold)) > max_width:
        size -= 6
    return sans(size, bold)


def wrap(draw: ImageDraw.ImageDraw, text: str, face, max_width: int) -> list[str]:
    lines: list[str] = []
    for word in text.split():
        trial = f"{lines[-1]} {word}" if lines else word
        if lines and draw.textlength(trial, font=face) <= max_width:
            lines[-1] = trial
        else:
            lines.append(word)
    return lines


_NUMBER = re.compile(r"^([^\d]*)([\d,]+(?:\.\d+)?)(.*)$")


def counting(value: str, k: float) -> str:
    """`value` with its leading number counted up to `k` of the way ("1,234" -> "617" at 0.5)."""
    match = _NUMBER.match(value)
    if not match or k >= 1:
        return value
    prefix, number, suffix = match.groups()
    target = float(number.replace(",", ""))
    current = target * k
    text = f"{current:,.{len(number.split('.')[1])}f}" if "." in number else f"{round(current):,}"
    if "," not in number:
        text = text.replace(",", "")
    return f"{prefix}{text}{suffix}"


def rounded(draw: ImageDraw.ImageDraw, box, radius: int, fill=None, outline=None, width: int = 1) -> None:
    x0, y0, x1, y1 = box
    if x1 - x0 < 1 or y1 - y0 < 1:
        return
    radius = int(min(radius, (x1 - x0) / 2, (y1 - y0) / 2))
    draw.rounded_rectangle((x0, y0, x1, y1), radius=radius, fill=fill, outline=outline, width=width)


# -- Shared scene parts ----------------------------------------------------------------


class Ctx:
    """What every scene needs: the beat, the theme, and derived colours."""

    def __init__(self, highlight: Highlight, stats: Stats, theme: Theme, tone: str):
        self.h = highlight
        self.stats = stats
        self.theme = theme
        self.tone = tone
        self.accent: RGB = theme.accent
        self.text: RGB = theme.text
        self.dim: RGB = theme.dim
        self.panel: RGB = mix(theme.bottom, (255, 255, 255), 0.07)
        self.empty: RGB = mix(theme.bottom, (255, 255, 255), 0.10)
        self.roast: RGB = TONE_TAG["roast"][1]
        self.props: RGB = TONE_TAG["compliment"][1]
        self.mark: RGB = self.props if tone == "compliment" else self.roast  # what the scene points at


def headline(area: Image.Image, ctx: Ctx, t: float) -> None:
    """Tag, the figure (counting up), and its label: the top of every scene."""
    draw = ImageDraw.Draw(area)
    tag, colour = TONE_TAG.get(ctx.tone, TONE_TAG["roast"])
    pop = ease_out(phase(t, 0.0, 0.35))
    if pop > 0:
        face = sans(34)
        width = draw.textlength(tag, font=face) + 48
        x, y = MARGIN, 40 + round(20 * (1 - pop))
        rounded(draw, (x, y, x + width, y + 60), 30, fill=colour)
        draw.text((x + 24, y + 30), tag, font=face, fill=(12, 14, 18), anchor="lm")

    rise = ease_out(phase(t, 0.1, 0.5))
    if rise > 0:
        value = counting(ctx.h.value, ease_out(phase(t, 0.1, 0.9)))
        face = fit(draw, ctx.h.value, WIDTH - 2 * MARGIN, 190, 80)
        y = 120 + round(40 * (1 - rise))
        draw.text((WIDTH / 2, y), value, font=face, fill=ctx.accent, anchor="mt")
        label_face = sans(50)
        for n, line in enumerate(wrap(draw, ctx.h.label, label_face, WIDTH - 2 * MARGIN)[:2]):
            draw.text((WIDTH / 2, y + 225 + n * 62), line, font=label_face, fill=ctx.text, anchor="mt")


# -- Contribution graph --------------------------------------------------------------------


def calendar_scene(ctx: Ctx, mode: str) -> Draw:
    """The year as a GitHub-style contribution graph, in two strips of 27 weeks.

    The cells fill in over the first moments, then the part the beat is about is outlined: the
    silence, the streak, the last 60 days, or the busiest day.
    """
    days = ctx.stats.calendar
    if not days:
        return fallback_scene(ctx)
    first = days[0].date
    sunday = first - timedelta(days=(first.weekday() + 1) % 7)
    weeks = (days[-1].date - sunday).days // 7 + 1
    per_strip = math.ceil(weeks / 2)
    cell, gap = 26, 6
    pitch = cell + gap
    grid_width = per_strip * pitch - gap
    x0 = (WIDTH - grid_width) // 2
    strip_tops = [VIZ_TOP + 110, VIZ_TOP + 110 + 7 * pitch + 120]

    counts = sorted({d.count for d in days if d.count})
    def level(count: int) -> float:
        if not count:
            return 0.0
        rank = counts.index(count) / max(1, len(counts) - 1)
        return 0.35 + 0.65 * rank

    cells = []  # (x, y, day, count)
    for d in days:
        week = (d.date - sunday).days // 7
        strip, column = divmod(week, per_strip)
        row = (d.date.weekday() + 1) % 7
        cells.append((x0 + column * pitch, strip_tops[min(strip, 1)] + row * pitch, d.date, d.count))

    s = ctx.stats
    focus: tuple[date, date] | None = None
    if mode == "gap" and s.longest_gap.start:
        focus = (s.longest_gap.start, s.longest_gap.end)
    elif mode == "streak" and s.longest_streak.start:
        focus = (s.longest_streak.start, s.longest_streak.end)
    elif mode == "current" and s.current_streak:
        end = days[-1].date if days[-1].count else days[-1].date - timedelta(days=1)
        focus = (end - timedelta(days=s.current_streak - 1), end)
    elif mode == "recent":
        focus = (days[-1].date - timedelta(days=RECENT_DAYS - 1), days[-1].date)
    elif mode == "busiest" and s.busiest_day:
        focus = (s.busiest_day.date, s.busiest_day.date)

    months = []
    for d in days:
        if d.date.day == 1 or d is days[0]:
            week = (d.date - sunday).days // 7
            strip, column = divmod(week, per_strip)
            months.append((x0 + column * pitch, strip_tops[min(strip, 1)] - 44, f"{d.date:%b}"))

    sweep_end = 1.4

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        shown = ease_in_out(phase(t, 0.2, sweep_end - 0.2))
        visible = math.ceil(shown * len(cells))
        label_face = sans(26, bold=False)
        for x, y, text in months:
            if x + 40 < x0 + grid_width:
                draw.text((x, y), text, font=label_face, fill=ctx.dim)

        emphasis = ease_out(phase(t, sweep_end, 0.6)) if focus else 0.0
        outline = focus is not None and (focus[1] - focus[0]).days < 75 and mode != "busiest"
        for n, (x, y, day, count) in enumerate(cells):
            inside = focus is not None and focus[0] <= day <= focus[1]
            if n >= visible:
                colour = mix(ctx.theme.bottom, ctx.empty, 0.4)
            elif count:
                colour = mix(ctx.empty, ctx.accent, level(count))
            else:
                colour = ctx.empty
            if focus and not inside:
                colour = mix(colour, ctx.theme.bottom, 0.55 * emphasis)
            elif inside and not outline and mode != "busiest":
                colour = mix(colour, ctx.mark, 0.45 * emphasis)
            grow = 0
            if inside and mode == "busiest":
                grow = round(10 * emphasis * (0.6 + 0.4 * math.sin(t * 6)))
            rounded(draw, (x - grow, y - grow, x + cell + grow, y + cell + grow), 6, fill=colour)
            if inside and emphasis > 0 and outline:
                draw.rounded_rectangle((x - 3, y - 3, x + cell + 3, y + cell + 3), radius=8, outline=ctx.mark, width=3)

        legend_y = strip_tops[1] + 7 * pitch + 40
        if focus and emphasis > 0:
            start, end = focus
            span = (end - start).days + 1
            text = f"{start:%b} {start.day}" + (f" – {end:%b} {end.day} · {span} days" if span > 1 else "")
            draw.text((WIDTH / 2, legend_y), text, font=sans(40), fill=ctx.mark, anchor="mt")
        elif shown >= 1:
            active = sum(1 for d in days if d.count)
            draw.text((WIDTH / 2, legend_y), f"{active} active days · {sum(d.count for d in days):,} contributions", font=sans(38, False), fill=ctx.dim, anchor="mt")

    return draw_frame


# -- 24-hour clock ------------------------------------------------------------------------


def clock_scene(ctx: Ctx, mode: str) -> Draw:
    """Commits by hour of day, as bars around a clock face. Midnight sits at the top."""
    hours = ctx.stats.hour_commits
    top = max(hours) or 1
    cx, cy = WIDTH // 2, (VIZ_TOP + VIZ_BOTTOM) // 2 - 10
    inner, outer = 120, 340
    lit = set(range(0, 5)) if mode == "night" else {ctx.stats.busiest_hour} if ctx.stats.busiest_hour is not None else set()

    def point(hour: float, radius: float) -> tuple[float, float]:
        angle = math.radians(hour / 24 * 360 - 90)
        return cx + radius * math.cos(angle), cy + radius * math.sin(angle)

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        draw.ellipse((cx - inner + 8, cy - inner + 8, cx + inner - 8, cy + inner - 8), outline=ctx.empty, width=4)
        if mode == "night":
            wedge = ease_out(phase(t, 1.2, 0.6))
            if wedge > 0:
                draw.pieslice((cx - outer - 20, cy - outer - 20, cx + outer + 20, cy + outer + 20), -90, -90 + 75 * wedge, fill=mix(ctx.theme.bottom, ctx.mark, 0.22))
        for hour in range(24):
            grow = ease_out(phase(t, 0.3 + hour * 0.03, 0.7))
            length = (outer - inner) * (0.04 + 0.96 * hours[hour] / top) * grow
            a, b = point(hour + 0.5, inner), point(hour + 0.5, inner + max(length, 4))
            highlighted = hour in lit and phase(t, 1.2, 0.01) >= 1
            colour = ctx.mark if highlighted else mix(ctx.empty, ctx.accent, 0.35 + 0.65 * hours[hour] / top)
            draw.line((a, b), fill=colour, width=30)
        label = sans(32)
        for hour, text in ((0, "12 AM"), (6, "6 AM"), (12, "12 PM"), (18, "6 PM")):
            x, y = point(hour, outer + 70)
            draw.text((x, y), text, font=label, fill=ctx.dim, anchor="mm")
        centre = "midnight–5 AM" if mode == "night" else ctx.h.value
        draw.text((cx, cy), centre, font=fit(draw, centre, 2 * inner - 40, 44, 26), fill=ctx.text, anchor="mm")

    return draw_frame


# -- Week bars -----------------------------------------------------------------------------


def weekday_scene(ctx: Ctx, mode: str) -> Draw:
    """Contributions per day of the week. The day (or weekend) the beat is about is coloured."""
    values = ctx.stats.weekday_contributions
    top = max(values) or 1
    if mode == "weekend":
        lit = {5, 6}
    elif mode == "friday":
        lit = {4}
    else:
        lit = {values.index(top)}
    bar, gap = 96, 30
    x0 = (WIDTH - (7 * bar + 6 * gap)) // 2
    base, height = VIZ_BOTTOM - 110, VIZ_BOTTOM - 110 - (VIZ_TOP + 60)

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        colour_in = phase(t, 1.3, 0.01)
        for n in range(7):
            grow = ease_out(phase(t, 0.3 + n * 0.08, 0.7))
            h = max(8, height * values[n] / top * grow)
            x = x0 + n * (bar + gap)
            colour = ctx.mark if n in lit and colour_in >= 1 else mix(ctx.empty, ctx.accent, 0.3 + 0.5 * values[n] / top)
            rounded(draw, (x, base - h, x + bar, base), 14, fill=colour)
            draw.text((x + bar / 2, base + 28), WEEKDAYS[n][:3], font=sans(34), fill=ctx.text if n in lit else ctx.dim, anchor="mt")
            if grow >= 1:
                draw.text((x + bar / 2, base - h - 16), f"{values[n]:,}", font=sans(30, False), fill=ctx.dim, anchor="mb")

    return draw_frame


# -- Terminal: git log -------------------------------------------------------------------


def _log_lines(ctx: Ctx, mode: str) -> tuple[list[LogLine], re.Pattern | None, int | None]:
    """Which commits to show, what to highlight in them, and which line to stop on."""
    log = ctx.stats.commit_log
    word = mode.split(":", 1)[1] if ":" in mode else None
    if word and word in ROAST_WORDS:
        pattern = re.compile(ROAST_WORDS[word], re.IGNORECASE)
        matching = [line for line in log if pattern.search(line.headline)]
        return (matching or log)[:24], pattern, None
    if mode == "repeated" and ctx.stats.most_repeated_message:
        text = ctx.stats.most_repeated_message.text.lower()
        matching = [line for line in log if line.headline.lower() == text]
        return matching[:24], re.compile(re.escape(ctx.stats.most_repeated_message.text), re.IGNORECASE), None
    if mode == "one_word":
        return [line for line in log if len(line.headline.split()) == 1][:24], re.compile(r"^.+$"), None
    if mode == "shortest" and ctx.stats.shortest_message:
        text = ctx.stats.shortest_message.text
        index = next((i for i, line in enumerate(log) if line.headline == text), None)
        if index is None:
            return log[:16], None, None
        window = log[max(0, index - 10) : index + 6]
        return window, None, window.index(log[index])
    return log[:24], None, None


def terminal_scene(ctx: Ctx, mode: str) -> Draw:
    """A terminal running `git log --oneline` over the user's own commits."""
    if not ctx.stats.commit_log:
        return fallback_scene(ctx)
    if mode == "biggest":
        return diffstat_scene(ctx)
    lines, pattern, stop = _log_lines(ctx, mode)
    if not lines:
        return fallback_scene(ctx)
    box = (MARGIN - 20, VIZ_TOP + 10, WIDTH - MARGIN + 20, VIZ_BOTTOM)
    face, size = mono(30), 30
    line_height = 46
    text_x = box[0] + 34
    max_chars = (box[2] - box[0] - 68) // round(size * 0.6)
    command = "git log --oneline"
    rows_fit = (box[3] - box[1] - 150) // line_height

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        rounded(draw, box, 22, fill=(13, 17, 23), outline=(48, 54, 61), width=2)
        for n, colour in enumerate(((255, 95, 86), (255, 189, 46), (39, 201, 63))):
            draw.ellipse((box[0] + 26 + n * 34, box[1] + 22, box[0] + 46 + n * 34, box[1] + 42), fill=colour)
        y = box[1] + 74
        typed = command[: round(len(command) * phase(t, 0.3, 0.6))]
        draw.text((text_x, y), "$ ", font=face, fill=(126, 231, 135))
        draw.text((text_x + draw.textlength("$ ", font=face), y), typed, font=face, fill=(230, 237, 243))
        y += line_height + 8

        shown = int(max(0.0, t - 0.95) / 0.11)
        # Scroll once the window is full, so the newest printed line stays in view.
        offset = max(0, min(shown, len(lines)) - rows_fit)
        for n, line in enumerate(lines[offset : min(shown, len(lines))]):
            index = n + offset
            text = line.headline if len(line.headline) <= max_chars - 8 else line.headline[: max_chars - 9] + "…"
            oid = line.oid or "•••••••"
            draw.text((text_x, y), oid, font=face, fill=(242, 204, 96))
            x = text_x + draw.textlength(oid + " ", font=face)
            stopped = stop is not None and index == stop
            colour = (230, 237, 243)
            if stop is not None and index != stop and shown > stop:
                colour = (110, 118, 129)
            if stopped:
                rounded(draw, (x - 10, y - 6, x + draw.textlength(text, font=face) + 10, y + size + 10), 8, fill=mix((13, 17, 23), ctx.mark, 0.35))
            match = pattern.search(text) if pattern else None
            if match and phase(t, 1.0, 0.01) >= 1:
                before, hit, after = text[: match.start()], text[match.start() : match.end()], text[match.end() :]
                draw.text((x, y), before, font=face, fill=colour)
                x2 = x + draw.textlength(before, font=face)
                draw.text((x2, y), hit, font=face, fill=ctx.mark)
                draw.text((x2 + draw.textlength(hit, font=face), y), after, font=face, fill=colour)
            else:
                draw.text((x, y), text, font=face, fill=colour)
            y += line_height
        if shown >= len(lines) and int(t * 2) % 2 == 0:
            draw.rectangle((text_x, y + 4, text_x + 18, y + size + 4), fill=(230, 237, 243))

    return draw_frame


def diffstat_scene(ctx: Ctx) -> Draw:
    """`git show --stat` for the biggest commit: one huge green bar."""
    big = ctx.stats.biggest_commit
    box = (MARGIN - 20, VIZ_TOP + 10, WIDTH - MARGIN + 20, VIZ_BOTTOM - 200)
    face = mono(30)

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        rounded(draw, box, 22, fill=(13, 17, 23), outline=(48, 54, 61), width=2)
        x, y = box[0] + 34, box[1] + 50
        draw.text((x, y), "$ git show --stat", font=face, fill=(126, 231, 135))
        if t > 0.9:
            title = big.headline if big and big.headline else "(a commit in a private repo)"
            for n, line in enumerate(wrap(draw, title, face, box[2] - box[0] - 68)[:3]):
                draw.text((x, y + 70 + n * 44), line, font=face, fill=(230, 237, 243))
        grow = ease_out(phase(t, 1.2, 1.2))
        bar_y = box[1] + 300
        width = (box[2] - box[0] - 68) * grow
        rounded(draw, (x, bar_y, x + width, bar_y + 60), 10, fill=(63, 185, 80))
        if big:
            files = f"{big.files} files changed, " if big.files else ""
            draw.text((x, bar_y + 100), f"{files}{counting(f'{big.additions:,}', grow)} insertions(+)", font=face, fill=(63, 185, 80))

    return draw_frame


# -- Languages -------------------------------------------------------------------------------


def languages_scene(ctx: Ctx) -> Draw:
    """The language bar from a GitHub profile, then the list under it."""
    langs = ctx.stats.languages[:6]
    if not langs:
        return fallback_scene(ctx)
    colours = [hex_rgb(LANGUAGE_COLOURS.get(lang.name, _FALLBACK_COLOURS[n % len(_FALLBACK_COLOURS)])) for n, lang in enumerate(langs)]
    total = sum(lang.share for lang in langs)
    bar_x0, bar_x1, bar_y = MARGIN, WIDTH - MARGIN, VIZ_TOP + 90

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        grow = ease_in_out(phase(t, 0.4, 1.0))
        rounded(draw, (bar_x0, bar_y, bar_x1, bar_y + 44), 22, fill=ctx.empty)
        x = bar_x0
        for lang, colour in zip(langs, colours):
            width = (bar_x1 - bar_x0) * lang.share / total * grow
            draw.rectangle((x, bar_y, x + width, bar_y + 44), fill=colour)
            x += width
        # Round the ends of the filled bar by masking with the track's shape.
        mask = Image.new("L", (bar_x1 - bar_x0, 44), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, bar_x1 - bar_x0 - 1, 43), radius=22, fill=255)
        crop = area.crop((bar_x0, bar_y, bar_x1, bar_y + 44))
        background = Image.new("RGB", crop.size, ctx.theme.bottom)
        area.paste(Image.composite(crop, background, mask), (bar_x0, bar_y))

        for n, (lang, colour) in enumerate(zip(langs, colours)):
            appear = ease_out(phase(t, 1.1 + n * 0.15, 0.4))
            if appear <= 0:
                continue
            y = bar_y + 130 + n * 100 + round(20 * (1 - appear))
            first = n == 0
            draw.ellipse((MARGIN, y + 8, MARGIN + 36, y + 44), fill=colour)
            draw.text((MARGIN + 60, y), lang.name, font=sans(46 if first else 40), fill=ctx.text if first else ctx.dim)
            draw.text((WIDTH - MARGIN, y), f"{lang.share * 100:.0f}%", font=sans(46 if first else 40), fill=ctx.accent if first else ctx.dim, anchor="ra")

    return draw_frame


# -- Repositories -------------------------------------------------------------------------


def repos_scene(ctx: Ctx, mode: str) -> Draw:
    """New repositories as cards; the abandoned ones fade to grey with their short life story."""
    repos = ctx.stats.new_repos[-8:]
    if not repos:
        return fallback_scene(ctx)
    columns, gap = 2, 30
    card_w = (WIDTH - 2 * MARGIN - gap) // columns
    card_h = 170
    rows = math.ceil(len(repos) / columns)
    y0 = VIZ_TOP + max(20, (VIZ_BOTTOM - VIZ_TOP - rows * (card_h + gap)) // 2)

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        judged = phase(t, 0.6 + len(repos) * 0.12 + 0.3, 0.6)
        for n, repo in enumerate(repos):
            appear = ease_out(phase(t, 0.5 + n * 0.12, 0.35))
            if appear <= 0:
                continue
            row, column = divmod(n, columns)
            x = MARGIN + column * (card_w + gap)
            y = y0 + row * (card_h + gap) + round(30 * (1 - appear))
            dead = repo.abandoned and mode == "abandoned"
            fill = mix(ctx.panel, ctx.theme.bottom, 0.5 * judged) if dead else ctx.panel
            rounded(draw, (x, y, x + card_w, y + card_h), 20, fill=fill, outline=mix(ctx.panel, ctx.mark, judged) if dead else None, width=3)
            name, name_face = repo.name, sans(36)
            while draw.textlength(name, font=name_face) > card_w - 100 and len(name) > 4:
                name = name[:-2].rstrip("_-. ") + "…" if not name.endswith("…") else name[:-2] + "…"
            draw.text((x + 28, y + 26), name, font=name_face, fill=mix(ctx.text, ctx.dim, judged) if dead else ctx.text)
            if dead:
                lived = (repo.last_push - repo.created).days
                note = f"last push {lived} day{'s' if lived != 1 else ''} after creation" if lived else "never touched again"
                draw.text((x + 28, y + 90), note, font=sans(26, False), fill=mix(ctx.dim, ctx.mark, judged))
            else:
                draw.text((x + 28, y + 90), f"created {repo.created:%b} {repo.created.day}", font=sans(28, False), fill=ctx.dim)
                draw.ellipse((x + card_w - 52, y + 36, x + card_w - 28, y + 60), fill=ctx.props if mode != "abandoned" else ctx.accent)

    return draw_frame


def repo_bars_scene(ctx: Ctx) -> Draw:
    """Commits per repository, as horizontal bars."""
    repos = ctx.stats.top_repos[:6]
    if not repos:
        return fallback_scene(ctx)
    top = repos[0].commits or 1

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        for n, repo in enumerate(repos):
            grow = ease_out(phase(t, 0.4 + n * 0.12, 0.8))
            y = VIZ_TOP + 60 + n * 140
            name = repo.name.split("/")[-1]
            draw.text((MARGIN, y), name if len(name) <= 30 else name[:29] + "…", font=sans(36), fill=ctx.text if n == 0 else ctx.dim)
            width = (WIDTH - 2 * MARGIN - 140) * repo.commits / top * grow
            rounded(draw, (MARGIN, y + 54, MARGIN + max(width, 10), y + 100), 12, fill=ctx.mark if n == 0 else mix(ctx.empty, ctx.accent, 0.5))
            if grow > 0:
                draw.text((MARGIN + max(width, 10) + 20, y + 77), counting(str(repo.commits), grow), font=sans(36), fill=ctx.text, anchor="lm")

    return draw_frame


def star_scene(ctx: Ctx) -> Draw:
    """One big star that fills to the number of stars received (or stays hollow)."""
    cx, cy, outer, inner = WIDTH // 2, (VIZ_TOP + VIZ_BOTTOM) // 2, 330, 140
    points = []
    for n in range(10):
        radius = outer if n % 2 == 0 else inner
        angle = math.radians(-90 + n * 36)
        points.append((cx + radius * math.cos(angle), cy + radius * math.sin(angle)))
    hollow = ctx.stats.stars_received == 0

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        grow = ease_out(phase(t, 0.4, 0.8))
        scaled = [(cx + (x - cx) * grow, cy + (y - cy) * grow) for x, y in points]
        if grow <= 0:
            return
        if hollow:
            wobble = math.sin(t * 2.2) * 6
            draw.polygon([(x + wobble, y) for x, y in scaled], outline=ctx.dim, width=6)
        else:
            draw.polygon(scaled, fill=ctx.accent)

    return draw_frame


# -- Branches -----------------------------------------------------------------------------


def branch_scene(ctx: Ctx, mode: str) -> Draw:
    """A git graph. With no pull requests it is one straight line of commits into main."""
    s = ctx.stats
    dots = 11
    x_main = WIDTH // 2 - (0 if mode == "none" else 140)
    y0, y1 = VIZ_TOP + 70, VIZ_BOTTOM - 120
    step = (y1 - y0) / (dots - 1)
    merged, opened = s.prs_merged, s.prs_opened
    branches = [] if mode == "none" else [(2 + 3 * n, n < min(merged, 3)) for n in range(min(max(opened, 1), 3))]

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        shown = ease_in_out(phase(t, 0.4, 2.0)) * dots
        if shown <= 0:
            return
        line_end = y0 + step * min(shown, dots - 1)
        draw.line((x_main, y0, x_main, line_end), fill=ctx.accent, width=10)
        draw.text((x_main, y0 - 54), "main", font=mono(34), fill=ctx.accent, anchor="mm")
        for start, merged_back in branches:
            if shown < start + 1:
                continue
            bx = x_main + 280
            ya, yb = y0 + step * start, y0 + step * (start + 2)
            draw.line((x_main, ya, bx, ya + step * 0.5, bx, yb - step * 0.5), fill=ctx.props, width=8, joint="curve")
            if merged_back and shown >= start + 2:
                draw.line((bx, yb - step * 0.5, x_main, yb), fill=ctx.props, width=8)
            elif not merged_back:
                xx, yy = bx, yb - step * 0.5 + 34
                draw.line((xx - 14, yy - 14, xx + 14, yy + 14), fill=ctx.roast, width=7)
                draw.line((xx - 14, yy + 14, xx + 14, yy - 14), fill=ctx.roast, width=7)
        for n in range(dots):
            if n >= shown:
                break
            y = y0 + step * n
            draw.ellipse((x_main - 22, y - 22, x_main + 22, y + 22), fill=ctx.theme.bottom, outline=ctx.accent, width=8)
        if mode == "none" and shown >= dots:
            appear = ease_out(phase(t, 2.6, 0.5))
            if appear > 0:
                x = x_main + 140
                draw.text((x, (y0 + y1) / 2 - 40), "branches: 0", font=mono(36), fill=mix(ctx.theme.bottom, ctx.mark, appear))
                draw.text((x, (y0 + y1) / 2 + 20), f"reviews: {s.pr_reviews}", font=mono(36), fill=mix(ctx.theme.bottom, ctx.mark, appear))

    return draw_frame


# -- Lines added and deleted ------------------------------------------------------------------


def lines_scene(ctx: Ctx) -> Draw:
    s = ctx.stats
    top = max(s.lines_added, s.lines_deleted) or 1

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        for n, (label, value, colour) in enumerate((("added", s.lines_added, (63, 185, 80)), ("deleted", s.lines_deleted, (248, 81, 73)))):
            grow = ease_out(phase(t, 0.5 + n * 0.3, 1.0))
            y = VIZ_TOP + 120 + n * 330
            sign = "+" if n == 0 else "−"
            draw.text((MARGIN, y), f"{sign}{counting(f'{value:,}', grow)} {label}", font=mono(48), fill=colour)
            width = (WIDTH - 2 * MARGIN) * value / top * grow
            rounded(draw, (MARGIN, y + 90, MARGIN + max(width, 8), y + 170), 14, fill=colour)

    return draw_frame


def _cover(image: Image.Image, width: int, height: int, zoom: float = 1.0, pan: float = 0.5) -> Image.Image:
    """`image` scaled to cover width x height at `zoom`, cropped; `pan` 0..1 slides along the longer leftover axis."""
    scale = max(width / image.width, height / image.height) * zoom
    scaled = image.resize((max(width, round(image.width * scale)), max(height, round(image.height * scale))), Image.BILINEAR)
    dx, dy = scaled.width - width, scaled.height - height
    x = round(dx * (pan if dx >= dy else 0.5))
    y = round(dy * (pan if dy > dx else 0.5))
    return scaled.crop((x, y, x + width, y + height))


def _scrim(width: int, height: int, colour: RGB, top: float = 0.45) -> Image.Image:
    """An RGBA gradient from transparent at `top` (fraction of height) to `colour` at the bottom."""
    scrim = Image.new("RGBA", (1, height), (*colour, 0))
    start = round(height * top)
    for y in range(start, height):
        scrim.putpixel((0, y), (*colour, round(245 * ((y - start) / max(1, height - start)) ** 0.9)))
    return scrim.resize((width, height))


def art_scene(ctx: Ctx, image_path: Path | None, clip_frames: list[Image.Image] | None = None) -> Draw:
    """A Magic Hour illustration filling the scene, with the figure typeset over its lower third.

    The still drifts slowly (a push-in and a slide); a hero beat's clip plays forwards and back
    in a loop instead. With no image the theme gradient stands in.
    """
    art = None
    if image_path and image_path.exists():
        with Image.open(image_path) as opened:
            art = opened.convert("RGB")
            art.load()
    scrim = _scrim(WIDTH, AREA_HEIGHT, ctx.theme.bottom, top=0.38)
    label_face = sans(54)
    base_line = round(AREA_HEIGHT * 0.66)

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        if clip_frames:
            n = len(clip_frames)
            cycle = 2 * (n - 1) or 1
            i = int(t * 30) % cycle
            i = i if i < n else cycle - i
            frame = clip_frames[i]
            area.paste(frame.resize((WIDTH, AREA_HEIGHT), Image.BILINEAR) if frame.size != (WIDTH, AREA_HEIGHT) else frame)
        elif art is not None:
            k = clamp(t / max(duration, 1.0))
            area.paste(_cover(art, WIDTH, AREA_HEIGHT, zoom=1.0 + 0.08 * k, pan=0.5 + 0.12 * math.sin(k * math.pi)))
        area.paste(scrim, (0, 0), scrim)
        draw = ImageDraw.Draw(area)

        tag, colour = TONE_TAG.get(ctx.tone, TONE_TAG["roast"])
        pop = ease_out(phase(t, 0.15, 0.35))
        rise = ease_out(phase(t, 0.25, 0.5))
        lines = wrap(draw, ctx.h.label, label_face, WIDTH - 2 * MARGIN)[:2]
        value_face = fit(draw, ctx.h.value, WIDTH - 2 * MARGIN, 250, 90)
        value_box = draw.textbbox((0, 0), ctx.h.value, font=value_face, anchor="la")
        value_h = value_box[3] - value_box[1]
        block_top = base_line - (value_box[3] + len(lines) * 66) // 2 + round(40 * (1 - rise))
        if pop > 0:
            face = sans(32)
            width = draw.textlength(tag, font=face) + 44
            y = block_top - 86
            rounded(draw, (MARGIN, y, MARGIN + width, y + 56), 28, fill=colour)
            draw.text((MARGIN + 22, y + 28), tag, font=face, fill=(12, 14, 18), anchor="lm")
        if rise > 0:
            value = counting(ctx.h.value, ease_out(phase(t, 0.25, 0.9)))
            draw.text((MARGIN - value_box[0], block_top), value, font=value_face, fill=ctx.accent, anchor="la")
            y = block_top + value_box[3] + 24
            for line in lines:
                draw.text((MARGIN, y), line, font=label_face, fill=ctx.text, anchor="la")
                y += 66

    return draw_frame


def fallback_scene(ctx: Ctx) -> Draw:
    """Just the headline, with a slow pulse under it."""

    def draw_frame(area: Image.Image, t: float, duration: float) -> None:
        headline(area, ctx, t)
        draw = ImageDraw.Draw(area)
        radius = 150 + 18 * math.sin(t * 2.5)
        cx, cy = WIDTH // 2, (VIZ_TOP + VIZ_BOTTOM) // 2
        draw.ellipse((cx - radius, cy - radius, cx + radius, cy + radius), outline=ctx.accent, width=6)

    return draw_frame


