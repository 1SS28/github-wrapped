def make_scene(highlight: Highlight, stats: Stats, theme: Theme, tone: str, *, art: Path | None = None, clip: list[Image.Image] | None = None, style: str = "data") -> Draw:
    ctx = Ctx(highlight, stats, theme, tone)
    if style == "wrapped":
        return art_scene(ctx, art, clip)
    if highlight.id.startswith("word_"):
        return terminal_scene(ctx, f"word:{highlight.id[5:]}")
    builder = _BY_ID.get(highlight.id)
    return builder(ctx) if builder else fallback_scene(ctx)
